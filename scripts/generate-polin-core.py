"""Generate smaller Polin webfonts without changing supported text or glyphs.

One-time tooling: fonttools[woff]==4.67.0, brotli==1.2.0.
Run from any directory. Original full fonts remain the fallback for rare text.
"""
import hashlib
import json
from pathlib import Path

import fontTools
from fontTools import subset
from fontTools.pens.recordingPen import DecomposingRecordingPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
FONTS = ROOT / "src/fonts"


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def ranges(points):
    groups = []
    for point in sorted(points):
        if groups and point == groups[-1][-1] + 1:
            groups[-1].append(point)
        else:
            groups.append([point])
    return ", ".join(f"U+{g[0]:X}" + (f"-{g[-1]:X}" if len(g) > 1 else "") for g in groups)


def outline(font, name):
    glyphs = font.getGlyphSet()
    pen = DecomposingRecordingPen(glyphs)
    glyphs[name].draw(pen)
    return pen.value


def names(font):
    return sorted((n.nameID, n.platformID, n.platEncID, n.langID, n.toBytes()) for n in font["name"].names)


# Keep complete common writing ranges, not just the letters in today's pages.
core = set(range(0x20, 0x100)) | set(range(0x590, 0x600))
core |= set(range(0xFB1D, 0xFB50)) | set(range(0x2000, 0x2070)) | set(range(0x20A0, 0x20D0))
# Current names and symbols also stay in one font, preserving cross-script shaping.
for path in sorted((ROOT / "src").rglob("*")):
    if path.suffix in {".md", ".astro", ".ts", ".mjs"}:
        core.update(map(ord, path.read_text()))

manifest = {"generator": "scripts/generate-polin-core.py", "fontTools": fontTools.__version__, "faces": []}
css = ["/* Generated by scripts/generate-polin-core.py. Full originals retain rare glyph coverage. */"]
for weight, style in [(400, "Regular"), (800, "Extrabold")]:
    original_path = FONTS / f"Polin-{style}.woff2"
    output_path = FONTS / f"Polin-{style}-core.woff2"
    original = TTFont(original_path, recalcTimestamp=False)
    source_map = original.getBestCmap()
    # Respect a font's no-subsetting bit rather than silently violating it.
    assert not original["OS/2"].fsType & 0x0100, "Font disallows subsetting"
    selected = sorted(core & source_map.keys())
    remaining = sorted(source_map.keys() - set(selected))
    options = subset.Options()
    options.name_IDs = ["*"]
    options.name_languages = ["*"]
    options.name_legacy = True
    options.glyph_names = True
    options.layout_features = ["*"]
    options.notdef_outline = True
    options.recommended_glyphs = True
    options.hinting = True
    # Preserve the original global bounding boxes too: rasterizers may use
    # these at small sizes even when each retained glyph's outline is identical.
    candidate = TTFont(original_path, recalcTimestamp=False, recalcBBoxes=False)
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=selected)
    subsetter.subset(candidate)
    candidate.flavor = "woff2"
    candidate.save(output_path)
    candidate = TTFont(output_path)
    candidate_map = candidate.getBestCmap()
    assert set(candidate_map) == set(selected)
    assert names(original) == names(candidate), "Name/license metadata changed"
    assert original["CFF "].cff.topDictIndex[0].FontBBox == candidate["CFF "].cff.topDictIndex[0].FontBBox
    for table, fields in {
        "head": ["unitsPerEm", "xMin", "yMin", "xMax", "yMax"],
        "hhea": ["ascent", "descent", "lineGap"],
        "OS/2": ["fsType", "usWeightClass", "sTypoAscender", "sTypoDescender", "sTypoLineGap", "usWinAscent", "usWinDescent"],
    }.items():
        for field in fields:
            assert getattr(original[table], field) == getattr(candidate[table], field), (table, field)
    for point in selected:
        before, after = source_map[point], candidate_map[point]
        assert original["hmtx"][before] == candidate["hmtx"][after], hex(point)
        assert outline(original, before) == outline(candidate, after), hex(point)
    # The font uses CFF outlines; retained hints are validated in the browser raster test.
    for points, path in [(selected, output_path), (remaining, original_path)]:
        css.extend([
            "@font-face {", "  font-family: 'Polin';",
            f"  src: url('./{path.name}') format('woff2');",
            f"  font-weight: {weight};", "  font-style: normal;", "  font-display: swap;",
            f"  unicode-range: {ranges(points)};", "}",
        ])
    manifest["faces"].append({
        "weight": weight, "original": original_path.name, "core": output_path.name,
        "originalBytes": original_path.stat().st_size, "coreBytes": output_path.stat().st_size,
        "originalSha256": digest(original_path), "coreSha256": digest(output_path),
        "coreCodepoints": selected, "remainingCodepoints": remaining,
        "validated": ["all cmap coverage retained", "disjoint unicode ranges", "identical outlines", "identical global bounding boxes", "identical horizontal and vertical metrics", "identical name and license metadata", "all layout features and hinting retained"],
    })
    print(f"{style}: {original_path.stat().st_size} -> {output_path.stat().st_size} bytes; {len(selected)} core + {len(remaining)} remaining characters")

(FONTS / "polin-core.css").write_text("\n".join(css) + "\n")
(FONTS / "polin-core.json").write_text(json.dumps(manifest, indent=2) + "\n")
